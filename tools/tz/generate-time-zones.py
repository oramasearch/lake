"""Writes src/control/time_zones.cpp: the IANA time zone names lake accepts for a schedule (lake#586).

A schedule's time zone becomes a Kubernetes CronJob's spec.timeZone, which Kubernetes refuses
unless the name is in the IANA database. lake checks the name against this list before it stores
the schedule. Regenerate it from a tz database (Python's zoneinfo reads /usr/share/zoneinfo, or
the `tzdata` package) when IANA publishes a release:

    python3 tools/tz/generate-time-zones.py > src/control/time_zones.cpp
"""
import pathlib
import zoneinfo

names = sorted(name for name in zoneinfo.available_timezones() if name != "Factory")
version = "unknown"
for root in zoneinfo.TZPATH:
    marker = pathlib.Path(root) / "+VERSION"
    if marker.exists():
        version = marker.read_text().strip()
        break
    marker = pathlib.Path(root) / "tzdata.zi"
    if marker.exists():
        version = marker.read_text().splitlines()[0].removeprefix("# version ").strip()
        break

print("// Generated by tools/tz/generate-time-zones.py from IANA tz database " + version + ".")
print("// Do not edit by hand; regenerate it (lake#586).")
print('#include "lake/control/agent_runs.hpp"')
print()
print("namespace lake::control {")
print()
print("const std::vector<std::string_view>& iana_time_zones() {")
print("    static const std::vector<std::string_view> names{")
for name in names:
    print(f'        "{name}",')
print("    };")
print("    return names;")
print("}")
print()
print("} // namespace lake::control")
