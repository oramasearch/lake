#!/usr/bin/env python3
"""Vendor agent-runtime's skills into lake (agent-runtime#7).

agent-runtime decides what each skill lets a person's agent do (its `skills.py`) and publishes it
as `skills.json`: each skill's name and label, and the Lake capabilities it grants, split into
reads (tools) and changes (proposals a person confirms) by Lake's own `x-lake-action`. lake uses it
twice, so it is written twice from that one file:

- src/control/agent_skills.cpp: the skills, and the reads each grants. A launched agent's key
  carries the reads of its own skills (control::agent_launch_scopes_for), never a change.
- frontend/src/pages/train/agent-skills.json: the skills the Agent Factory and the agent pages
  offer, with their labels.

    tools/agents/vendor-agent-skills.py ~/dev/oramasearch/codex-work/wt/agent-runtime/issue-7/skills.json
    tools/agents/vendor-agent-skills.py <skills.json> --check   # exit 1 when lake's copy differs
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CPP = ROOT / "src/control/agent_skills.cpp"
FRONTEND = ROOT / "frontend/src/pages/train/agent-skills.json"


def cpp(skills: list[dict]) -> str:
    lines = [
        "// Generated by tools/agents/vendor-agent-skills.py from agent-runtime's skills.json.",
        "// Do not edit by hand; regenerate it (agent-runtime#7).",
        '#include "lake/control/agent_runs.hpp"',
        "",
        "namespace lake::control {",
        "",
        "const std::vector<AgentSkill>& agent_skills() {",
        "    static const std::vector<AgentSkill> skills{",
    ]
    for skill in skills:
        lines.append(f'        AgentSkill{{"{skill["name"]}",')
        lines.append(f'                   "{skill["label"]}",')
        lines.append("                   {")
        lines += [f'                       "{name}",' for name in skill["reads"]]
        lines.append("                   }},")
    lines += ["    };", "    return skills;", "}", "", "} // namespace lake::control", ""]
    return "\n".join(lines)


def frontend(skills: list[dict]) -> str:
    return json.dumps([[skill["name"], skill["label"]] for skill in skills], indent=1) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("skills_json", type=pathlib.Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    skills = json.loads(args.skills_json.read_text())["skills"]
    outputs = {CPP: cpp(skills), FRONTEND: frontend(skills)}
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs.items()
                 if not path.exists() or path.read_text() != text]
        if stale:
            print("out of date: " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    for path, text in outputs.items():
        path.write_text(text)
        print(f"{len(skills)} skills -> {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
