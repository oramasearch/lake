#!/usr/bin/env node
// Embed the built web app (frontend/dist) into the lake binary: one C++ translation unit holding
// every file's bytes, its served path and its media type. lake serves `/index.html` for page
// routes and everything under `/ui/` (Vite's content-hashed output) immutable.
//
//   node tools/ui/embed-frontend.mjs <dist dir> <output .cpp>
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, sep } from "node:path";

const [distDir, outputFile] = process.argv.slice(2);
if (!distDir || !outputFile) {
  console.error("usage: embed-frontend.mjs <dist dir> <output .cpp>");
  process.exit(2);
}

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
  ".map": "application/json",
};

function walk(dir, found = []) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, found);
    else found.push(path);
  }
  return found;
}

let files;
try {
  files = walk(distDir).filter((path) => extname(path) !== ".map");
} catch {
  console.error(`embed-frontend: ${distDir} does not exist; run npm run build in frontend/ first`);
  process.exit(1);
}
if (!files.some((path) => relative(distDir, path) === "index.html")) {
  console.error(`embed-frontend: ${distDir} has no index.html`);
  process.exit(1);
}

const lines = [
  "// Generated by tools/ui/embed-frontend.mjs from frontend/dist. Do not edit.",
  '#include "lake/api/web_app.hpp"',
  "",
  "#include <array>",
  "",
  "namespace lake::api {",
  "namespace {",
];
const entries = [];
files.forEach((path, index) => {
  const bytes = readFileSync(path);
  const served = "/" + relative(distDir, path).split(sep).join("/");
  const type = TYPES[extname(path)] ?? "application/octet-stream";
  const body = [];
  for (let i = 0; i < bytes.length; i += 24) {
    body.push("    " + Array.from(bytes.subarray(i, i + 24), (b) => `0x${b.toString(16).padStart(2, "0")}`).join(",") + ",");
  }
  lines.push(`constexpr unsigned char file_${index}[] = {`, ...(body.length ? body : ["    0x00,"]), "};");
  entries.push(`    WebAppAsset{"${served}", "${type}", std::string_view(reinterpret_cast<const char*>(file_${index}), ${bytes.length})},`);
});
lines.push(
  `const std::array<WebAppAsset, ${entries.length}> assets{{`,
  ...entries,
  "}};",
  "} // namespace",
  "",
  "std::span<const WebAppAsset> web_app_assets() {",
  "    return assets;",
  "}",
  "} // namespace lake::api",
  "",
);
mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, lines.join("\n"));
console.log(`embed-frontend: ${files.length} files from ${distDir}`);
